#!/usr/bin/env python3
"""
Draws the first pictures for build 52's things (weapons, armor, spells, familiars, runes,
trinkets, enemies and power-ups) as 12 x 12 PNGs in textures/, and adds their lines to
textures/index.json. Each picture is a small character map below, in the house style:
flat colors, a dark outline, chunky pixels.

    python tools/textures/arsenal-art.py           # writes only the pictures that don't exist yet
    python tools/textures/arsenal-art.py --force   # redraws them all (loses any repainting!)

These are meant to be repainted by hand: once a file exists this tool leaves it alone.
Runes are drawn on the Rune of Plenty's eight stones, with each new rune's own glyph carved in.
"""
import json
import os
import sys

from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TEX = os.path.join(ROOT, "textures")
FORCE = "--force" in sys.argv
K = "#1a1410"   # the outline

written, kept, index_add = [], [], {}


def hexrgb(h):
    h = h.lstrip("#")
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4)) + (255,)


def draw(rows, pal):
    assert len(rows) == 12 and all(len(r) == 12 for r in rows), rows
    im = Image.new("RGBA", (12, 12), (0, 0, 0, 0))
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch == ".":
                continue
            col = K if ch == "k" else pal[ch]
            im.putpixel((x, y), hexrgb(col))
    return im


def save(tex_id, rel, im):
    path = os.path.join(TEX, rel)
    index_add[tex_id] = rel.replace(os.sep, "/")
    if os.path.exists(path) and not FORCE:
        kept.append(rel)
        return
    os.makedirs(os.path.dirname(path), exist_ok=True)
    im.save(path)
    written.append(rel)


def grid(s):
    rows = [r for r in s.strip("\n").split("\n")]
    rows = [r.ljust(12, ".")[:12] for r in rows]
    while len(rows) < 12:
        rows.append("." * 12)
    return rows


